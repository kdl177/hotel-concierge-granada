#!/usr/bin/env python3
"""
Builds the self-hosted icon font of the concierge (no Google Fonts at runtime).

  pip install fonttools brotli
  npm pack material-symbols && tar xzf material-symbols-*.tgz package/material-symbols-rounded.woff2
  python3 tools/icons/build-icons.py package/material-symbols-rounded.woff2

Takes Material Symbols Rounded (Apache-2.0, Google), pins the variable axes
(FILL 0, wght 400, GRAD 0, opsz 24) and keeps only the icons used by the code
plus a curated set offered in the admin icon picker. Icons are addressed by
code point (src/design/icons.js), so no ligature tables are shipped.
Output: public/fonts/concierge-symbols.woff2 + src/design/icons.js
"""
import glob, json, re, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = Path(__file__).resolve().parents[2]
SRC = sys.argv[1] if len(sys.argv) > 1 else 'package/material-symbols-rounded.woff2'

# Icons a hotel admin can pick for services, quick actions and places.
CURATED = """
ac_unit accessible airport_shuttle apartment attractions bakery_dining beach_access bed bedtime breakfast_dining
brunch_dining cake camera_alt car_rental casino castle celebration church coffee concierge_bell cookie
deck dinner_dining directions_boat directions_car dry_cleaning ev_station event fastfood festival fireplace
flight hiking hot_tub icecream iron kayaking kitchen liquor local_activity local_atm local_cafe local_convenience_store
local_dining local_florist local_hospital local_laundry_service local_library local_mall local_pharmacy local_pizza
lunch_dining luggage meeting_room mosque nightlife nights_stay outdoor_grill palette paragliding pedal_bike
photo_camera pool ramen_dining restaurant_menu rowing sailing sauna scuba_diving self_improvement shower
signpost skateboarding sports_bar sports_golf sports_tennis stadium storefront surfing synagogue temple_buddhist
theater_comedy theaters tour translate tv vaccines volunteer_activism water_drop wine_bar yard wc smoking_rooms
smoke_free no_meals baby_changing_station child_friendly elevator stairs local_drink sledding snowboarding
downhill_skiing forest volcano waves sunny_snowing beach_access kitesurfing
""".split()

font = TTFont(SRC)
cmap = font.getBestCmap()
char_of = {g: chr(c) for c, g in cmap.items()}
glyph_cp = {}
for c, g in cmap.items():
    glyph_cp.setdefault(g, c)
names = {}
for lookup in font['GSUB'].table.LookupList.Lookup:
    for st in lookup.SubTable:
        if lookup.LookupType == 7:
            st = st.ExtSubTable
        for first, ligs in getattr(st, 'ligatures', {}).items():
            for lg in ligs:
                n = ''.join(char_of.get(x, '?') for x in [first] + lg.Component)
                if lg.LigGlyph in glyph_cp:
                    names[n] = glyph_cp[lg.LigGlyph]

tokens = set()
files = glob.glob(str(ROOT / 'src/concierge/**/*.js'), recursive=True) + glob.glob(str(ROOT / 'src/backoffice/*.js')) + [str(ROOT / 'server/app/api.js'), str(ROOT / 'server/app/places.js')]
for fn in files:
    tokens |= set(re.findall(r"['\"`]([a-z][a-z0-9_]{1,40})['\"`]", Path(fn).read_text()))
wanted = sorted({t for t in tokens | set(CURATED) if t in names})
print(f'{len(wanted)} icons')

static = instancer.instantiateVariableFont(font, {'FILL': 0, 'wght': 400, 'GRAD': 0, 'opsz': 24})
opts = subset.Options()
opts.flavor = 'woff2'
opts.layout_features = []
opts.name_IDs = ['*']
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=[names[n] for n in wanted])
sub.subset(static)
out = ROOT / 'public/fonts/concierge-symbols.woff2'
out.parent.mkdir(parents=True, exist_ok=True)
static.flavor = 'woff2'
static.save(out)
print(f'{out.relative_to(ROOT)}: {out.stat().st_size // 1024} KB')

curated = sorted(n for n in CURATED if n in names)
js = ['/** Generated by tools/icons/build-icons.py — icon name → code point in public/fonts/concierge-symbols.woff2. */',
      f'export const ICONS = {json.dumps({n: names[n] for n in wanted}, separators=(",", ":"))};',
      f'/** Icons offered in the admin icon picker. */',
      f'export const PICKER_ICONS = {json.dumps(curated)};',
      "/** HTML for an icon: only known names render (anything else shows 'help'). */",
      "export const glyph = (name) => `&#x${(ICONS[name] ?? ICONS.help).toString(16)};`;",
      '']
(ROOT / 'src/design/icons.js').write_text('\n'.join(js))
