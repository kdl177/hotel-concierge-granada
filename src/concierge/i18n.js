let current = detectLanguage();

export function detectLanguage() {
  try {
    const stored = localStorage.getItem('concierge.lang');
    if (stored && LANGS.includes(stored)) return stored;
  } catch {}
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : 'es';
}

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  current = lang;
  try {
    localStorage.setItem('concierge.lang', lang);
  } catch {}
  document.documentElement.lang = lang;
}

/** UI string by key, with {placeholders}. */
export function t(key, vars) {
  let s = STRINGS[current]?.[key] ?? STRINGS.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

/** Pick a translated field from content objects ({es, en, fr, de}). */
export function L(obj, lang = current) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] ?? obj.es ?? obj.en ?? Object.values(obj)[0] ?? '';
}
